import AppKit
import ImageIO
import Observation

/// One thing that was on the pasteboard.
struct ClipItem: Identifiable {
    enum Payload {
        case text(String)
        /// Original bytes (to copy back losslessly) plus a small thumbnail for the row.
        case image(Data, NSPasteboard.PasteboardType, thumbnail: NSImage)
    }

    let id = UUID()
    let payload: Payload
    let kind: ClipKind
    /// One line, whitespace collapsed, short enough to lay out cheaply.
    let preview: String
    var date = Date()

    var text: String? { if case .text(let s) = payload { return s } else { return nil } }
    var imageData: Data? { if case .image(let d, _, _) = payload { return d } else { return nil } }
    var thumbnail: NSImage? { if case .image(_, _, let t) = payload { return t } else { return nil } }
}

/// The one shortcut a row offers on hover, derived from what was detected.
struct ClipAction {
    enum Effect { case copy(String), open(URL) }
    let title: String
    let effect: Effect
}

extension ClipItem {
    var action: ClipAction? {
        switch kind {
        case .json(let pretty?): return ClipAction(title: "Format", effect: .copy(pretty))
        case .timestamp(let d): return ClipAction(title: "Copy date", effect: .copy(ClipDetector.iso8601(d)))
        case .jwt(_, _, let payload): return ClipAction(title: "Decode", effect: .copy(payload))
        case .base64(let decoded): return ClipAction(title: "Decode", effect: .copy(decoded))
        case .url(let url): return ClipAction(title: "Open", effect: .open(url))
        default: return nil
        }
    }
}

/// Recent clipboard items for the Shelf. Memory only, never written to disk.
///
/// macOS has no pasteboard-changed notification, so this polls `changeCount` (an integer read,
/// the standard approach) and does nothing else unless it moved. Parsing and thumbnailing run on
/// a background queue so a big copy never stalls the island.
@Observable
final class ClipboardHistory {
    private(set) var items: [ClipItem] = []

    static let limit = 30
    static let maxTextLength = 200_000
    static let maxImageBytes = 10 * 1024 * 1024
    /// Total image bytes kept; the oldest images go first beyond this.
    static let imageBudget = 64 * 1024 * 1024

    /// Markers password managers and other apps set on secrets and throwaway data
    /// (see nspasteboard.org). Anything carrying one is never recorded.
    static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
    ]
    /// Copies made while one of these is frontmost are skipped, marker or not.
    static let passwordManagerIDs = [
        "com.1password", "com.agilebits", "com.bitwarden", "com.dashlane",
        "com.apple.keychainaccess", "com.apple.passwords",
    ]
    static let passwordManagerNames: Set<String> = ["1Password", "Bitwarden", "Dashlane", "Keychain Access", "Passwords"]

    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var lastChange = 0
    /// Bumped on stop and clear so captures still in flight are dropped.
    @ObservationIgnored private var generation = 0
    @ObservationIgnored private let work = DispatchQueue(label: "isle.clipboard", qos: .utility)

    private var pasteboard: NSPasteboard { .general }

    // MARK: Watching

    /// Starts or stops watching. Stopping also forgets everything.
    func setWatching(_ on: Bool) {
        if on {
            guard timer == nil else { return }
            // Only what's copied from now on; whatever is already there may predate consent.
            lastChange = pasteboard.changeCount
            let t = Timer(timeInterval: 0.75, repeats: true) { [weak self] _ in self?.poll() }
            t.tolerance = 0.25
            RunLoop.main.add(t, forMode: .common)
            timer = t
        } else {
            timer?.invalidate()
            timer = nil
            clear()
        }
    }

    private func poll() {
        let pb = pasteboard
        let count = pb.changeCount
        guard count != lastChange else { return }
        lastChange = count
        let types = pb.types ?? []
        guard !types.isEmpty, !Self.isPrivate(types) else { return }
        // Copied files are the files shelf's business, not text (Finder also puts the name there).
        guard !types.contains(.fileURL) else { return }

        if let s = pb.string(forType: .string) {
            guard s.utf16.count <= Self.maxTextLength,
                  !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
            captureText(s)
        } else if let type = pb.availableType(from: [.png, .tiff]), let data = pb.data(forType: type),
                  data.count <= Self.maxImageBytes {
            captureImage(data, type: type)
        }
    }

    static func isPrivate(_ types: [NSPasteboard.PasteboardType]) -> Bool {
        if types.contains(where: { privateTypes.contains($0.rawValue) }) { return true }
        guard let app = NSWorkspace.shared.frontmostApplication else { return false }
        let id = app.bundleIdentifier?.lowercased() ?? ""
        return passwordManagerIDs.contains { id.hasPrefix($0) } || passwordManagerNames.contains(app.localizedName ?? "")
    }

    // MARK: Capture

    private func captureText(_ s: String) {
        if let i = items.firstIndex(where: { $0.text == s }) { return bump(i) }
        let gen = generation
        work.async { [weak self] in
            let item = ClipItem(payload: .text(s), kind: ClipDetector.classify(s), preview: Self.oneLine(s))
            DispatchQueue.main.async { self?.insert(item, generation: gen) }
        }
    }

    private func captureImage(_ data: Data, type: NSPasteboard.PasteboardType) {
        if let i = items.firstIndex(where: { $0.imageData == data }) { return bump(i) }
        let gen = generation
        work.async { [weak self] in
            guard let src = CGImageSourceCreateWithData(data as CFData, nil),
                  let thumb = CGImageSourceCreateThumbnailAtIndex(src, 0, [
                      kCGImageSourceCreateThumbnailFromImageAlways: true,
                      kCGImageSourceCreateThumbnailWithTransform: true,
                      kCGImageSourceThumbnailMaxPixelSize: 88,
                  ] as CFDictionary) else { return }
            let props = CGImageSourceCopyPropertiesAtIndex(src, 0, nil) as? [CFString: Any]
            let w = props?[kCGImagePropertyPixelWidth] as? Int ?? thumb.width
            let h = props?[kCGImagePropertyPixelHeight] as? Int ?? thumb.height
            let image = NSImage(cgImage: thumb, size: NSSize(width: thumb.width, height: thumb.height))
            let item = ClipItem(payload: .image(data, type, thumbnail: image), kind: .image(width: w, height: h),
                                preview: "Image \(w) × \(h)")
            DispatchQueue.main.async { self?.insert(item, generation: gen) }
        }
    }

    private func insert(_ item: ClipItem, generation gen: Int) {
        guard gen == generation else { return }
        var next = items
        next.removeAll { ($0.text != nil && $0.text == item.text) || ($0.imageData != nil && $0.imageData == item.imageData) }
        next.insert(item, at: 0)
        if next.count > Self.limit { next.removeLast(next.count - Self.limit) }
        var imageBytes = 0
        next = next.filter { clip in
            guard let d = clip.imageData else { return true }
            imageBytes += d.count
            return imageBytes <= Self.imageBudget || clip.id == item.id
        }
        items = next
    }

    /// Moves an existing item to the top, as if it had just been copied.
    private func bump(_ i: Int) {
        var item = items[i]
        item.date = Date()
        items.remove(at: i)
        items.insert(item, at: 0)
    }

    private static func oneLine(_ s: String) -> String {
        s.prefix(400).split(whereSeparator: \.isWhitespace).joined(separator: " ")
    }

    // MARK: Actions

    /// Puts an item back on the pasteboard and moves it to the top.
    func copy(_ item: ClipItem) {
        let pb = pasteboard
        pb.clearContents()
        switch item.payload {
        case .text(let s): pb.setString(s, forType: .string)
        case .image(let data, let type, _): pb.setData(data, forType: type)
        }
        lastChange = pb.changeCount
        if let i = items.firstIndex(where: { $0.id == item.id }) { bump(i) }
    }

    /// Runs a row's shortcut. Derived text goes to the pasteboard without joining the history.
    func perform(_ action: ClipAction) {
        switch action.effect {
        case .copy(let s):
            let pb = pasteboard
            pb.clearContents()
            pb.setString(s, forType: .string)
            lastChange = pb.changeCount
        case .open(let url):
            NSWorkspace.shared.open(url)
        }
    }

    func remove(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
    }

    func clear() {
        generation &+= 1
        guard !items.isEmpty else { return }
        items.removeAll()
    }
}
